#!/usr/bin/env python3
"""A központi, önkéntes támogatási kártya biztonságos beágyazása."""
import html
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
PROVIDERS = (
    ('revolut_me_url', 'revolut.me', 'Revolut.me'),
    ('ko_fi_url', 'ko-fi.com', 'Ko-fi'),
)
TEXT = {
    'hu': (
        'A fejlesztés támogatása',
        'Ha hasznosnak találod a programot, önkéntes támogatással segítheted a '
        'fejlesztését. A program minden funkciója és minden kiadott frissítése '
        'támogatás nélkül is ingyenesen elérhető. A támogatásért nem jár külön '
        'szolgáltatás vagy jogosultság.',
        'Támogatás: ',
        'új lapon nyílik meg',
    ),
    'en': (
        'Support development',
        'If you find the program useful, you can voluntarily support its '
        'development. Every feature and every published update is available '
        'free of charge, whether or not you contribute. Support does not '
        'provide any additional service or entitlement.',
        'Support via ',
        'opens in a new tab',
    ),
}


def validate_links(config):
    """Csak a tulajdonos által megadott, általános HTTPS profilcím fogadható el."""
    keys = {key for key, _, _ in PROVIDERS}
    if not isinstance(config, dict) or set(config) != keys:
        raise ValueError('A támogatási konfigurációban pontosan a két URL-kulcs szükséges.')
    links = {}
    for key, host, _ in PROVIDERS:
        value = config[key]
        if not isinstance(value, str):
            raise ValueError(f'{key}: szöveges URL szükséges.')
        value = value.strip()
        # Nincs összeg, lekérdezés, átirányító vagy nem jóváhagyott külső oldal.
        if value and not re.fullmatch(
            r'https://' + re.escape(host) + r'/[A-Za-z0-9][A-Za-z0-9._-]{0,99}/?', value
        ):
            raise ValueError(f'{key}: általános https://{host}/profil cím szükséges.')
        links[key] = value
    return links


def render_card(config, language):
    links = validate_links(config)
    if not any(links.values()):
        return ''
    title, copy, label, new_tab = TEXT[language]
    buttons = []
    for key, _, name in PROVIDERS:
        if not links[key]:
            continue
        text = label + name
        buttons.append(
            f'<a href="{html.escape(links[key], quote=True)}" target="_blank" '
            'rel="noopener noreferrer" referrerpolicy="no-referrer" '
            f'aria-label="{html.escape(text + " – " + new_tab, quote=True)}">'
            f'{html.escape(text)}</a>'
        )
    template = (ROOT / 'assets/web/support.html').read_text(encoding='utf-8')
    return template.replace('{{TITLE}}', html.escape(title)).replace(
        '{{COPY}}', html.escape(copy)).replace('{{LINKS}}', ''.join(buttons))


def build_header(config):
    lines = ['/* Generated by tools/prepare_support.py. */', '#pragma once']
    for language in TEXT:
        card = render_card(config, language)
        literal = json.dumps(card, ensure_ascii=False).replace('??', '?\\?')
        lines.append(f'static const char app_support_card_{language}[] = {literal};')
    return '\n'.join(lines) + '\n'


def prepare_support(check=False):
    config = json.loads((ROOT / 'assets/support-links.json').read_text(encoding='utf-8'))
    content = build_header(config)
    destination = ROOT / 'main/app_support_links.h'
    if check:
        if not destination.exists() or destination.read_text(encoding='utf-8') != content:
            raise ValueError('Elavult támogatási fejléc. Futtasd: python3 tools/prepare_web.py')
    else:
        destination.write_text(content, encoding='utf-8')


if __name__ == '__main__':
    if sys.argv[1:] not in ([], ['--check']):
        sys.exit('Usage: python3 tools/prepare_support.py [--check]')
    prepare_support(check=sys.argv[1:] == ['--check'])
