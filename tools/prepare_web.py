#!/usr/bin/env python3
"""Embed offline template manager and settings pages from editable HTML/JS sources."""
import json
import sys
from pathlib import Path
from prepare_support import prepare_support

ROOT = Path(__file__).resolve().parents[1]
CHECK = sys.argv[1:] == ['--check']
if sys.argv[1:] and not CHECK:
    sys.exit('Usage: python3 tools/prepare_web.py [--check]')

prepare_support(check=CHECK)


# Közös megjelenés: minden oldal ugyanazt a stíluslapot és felső menüt kapja.
# Beágyazva (nem külön kérésként), így az oldalak külső erőforrás nélkül működnek.
NAV = {
    'hu': (('home', '/', 'Kezdőlap'), ('settings', '/settings', 'Beállítások'),
           ('loxone', '/loxone', 'Loxone'), ('templates', '/templates', 'Sablonok'),
           ('backup', '/backup', 'Mentés'), ('update', '/update', 'Frissítés'),
           ('diagnostics', '/diagnostics', 'Diagnosztika')),
    'en': (('home', '/', 'Home'), ('settings', '/settings', 'Settings'),
           ('loxone', '/loxone', 'Loxone'), ('templates', '/templates', 'Templates'),
           ('backup', '/backup', 'Backup'), ('update', '/update', 'Update'),
           ('diagnostics', '/diagnostics', 'Diagnostics')),
}


def common_css():
    """A közös stíluslap sorvégek és behúzás nélkül (a bájtok a firmware-be kerülnek)."""
    css = (ROOT / 'assets/web/common.css').read_text(encoding='utf-8')
    return ''.join(line.strip() for line in css.splitlines())


def nav_html(language):
    label = 'Fő menü' if language == 'hu' else 'Main menu'
    links = ''.join(f"<a href='{href}' data-nav='{key}'>{text}</a>" for key, href, text in NAV[language])
    return (f"<header class='topbar'><a class='brand' href='/'>Zolee Energy Flow Display</a>"
            f"<nav aria-label='{label}'>{links}</nav></header>")


def c_literal(text):
    return json.dumps(text, ensure_ascii=False).replace('??', '?\\?')


def write_or_check(dest, content):
    if CHECK:
        if not dest.exists() or dest.read_text(encoding='utf-8') != content:
            sys.exit(f'Stale embedded web page: {dest.relative_to(ROOT)}. '
                     'Run: python3 tools/prepare_web.py')
    else:
        dest.write_text(content, encoding='utf-8')


def embed(html, js, placeholder, name, header):
    page = (ROOT / 'assets/web' / html).read_text(encoding='utf-8').replace(
        placeholder, (ROOT / 'assets/web' / js).read_text(encoding='utf-8'))
    page = page.replace('/*COMMON_CSS*/', common_css()).replace('<!--APP_NAV-->', nav_html('hu'))
    if html == 'loxone.html':
        icons = json.loads((ROOT / 'assets/loxone-home/catalog.json').read_text())['icons']
        compact = [{key: icon[key] for key in ('id', 'hu', 'en')} for icon in icons]
        home = (ROOT / 'assets/web/loxone-home.js').read_text().replace(
            '/*HOME_ICONS*/', json.dumps(compact, ensure_ascii=False, separators=(',', ':')))
        page = page.replace('/*HOME_JS*/', home)
        page = page.replace('/*SLAVES_JS*/', (ROOT / 'assets/web/loxone-slaves.js').read_text())
    lines = ['/* Generated by tools/prepare_web.py. */', '#pragma once',
             f'static const char {name}[] =']
    lines += [json.dumps(line + '\n', ensure_ascii=False).replace('??', '?\\?')
              for line in page.splitlines()]
    content = '\n'.join(lines) + ';\n'
    write_or_check(ROOT / 'main' / header, content)


embed('template-manager.html', 'template-manager.js', '/*MANAGER_JS*/',
      'template_manager_page', 'app_template_page.h')
embed('loxone.html', 'loxone.js', '/*LOXONE_JS*/',
      'app_loxone_page', 'app_loxone_page.h')
embed('settings.html', 'settings.js', '/*SETTINGS_JS*/',
      'app_settings_page', 'app_settings_page.h')
embed('backup.html', 'backup.js', '/*BACKUP_JS*/',
      'app_backup_page', 'app_backup_page.h')

# A C-ben összeállított oldalak (kezdőlap, frissítés, diagnosztika) makrókat kapnak.
style_header = '\n'.join([
    '/* Generated by tools/prepare_web.py from assets/web/common.css. */',
    '#pragma once',
    f'#define APP_WEB_CSS {c_literal(common_css())}',
    f'#define APP_WEB_NAV_HU {c_literal(nav_html("hu"))}',
    f'#define APP_WEB_NAV_EN {c_literal(nav_html("en"))}',
]) + '\n'
write_or_check(ROOT / 'main' / 'app_web_style.h', style_header)
