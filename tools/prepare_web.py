#!/usr/bin/env python3
"""Embed the offline template manager from editable HTML/JS sources."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
html=(ROOT/'assets/web/template-manager.html').read_text()
js=(ROOT/'assets/web/template-manager.js').read_text()
page=html.replace('/*MANAGER_JS*/',js)
lines=['/* Generated by tools/prepare_web.py. */','#pragma once','static const char template_manager_page[] =']
lines += [json.dumps(line+'\n',ensure_ascii=False) for line in page.splitlines()]
(ROOT/'main/app_template_page.h').write_text('\n'.join(lines)+';\n')
