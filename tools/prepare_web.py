#!/usr/bin/env python3
"""Embed offline template manager and settings pages from editable HTML/JS sources."""
import json
import sys
from pathlib import Path
from prepare_support import prepare_support

ROOT = Path(__file__).resolve().parents[1]
CHECK = sys.argv[1:] == ['--check']
if sys.argv[1:] and not CHECK:
    sys.exit('Usage: python3 tools/prepare_web.py [--check]')

prepare_support(check=CHECK)


def embed(html, js, placeholder, name, header):
    page = (ROOT / 'assets/web' / html).read_text(encoding='utf-8').replace(
        placeholder, (ROOT / 'assets/web' / js).read_text(encoding='utf-8'))
    if html == 'loxone.html':
        icons = json.loads((ROOT / 'assets/loxone-home/catalog.json').read_text())['icons']
        compact = [{key: icon[key] for key in ('id', 'hu', 'en')} for icon in icons]
        home = (ROOT / 'assets/web/loxone-home.js').read_text().replace(
            '/*HOME_ICONS*/', json.dumps(compact, ensure_ascii=False, separators=(',', ':')))
        page = page.replace('/*HOME_JS*/', home)
        page = page.replace('/*SLAVES_JS*/', (ROOT / 'assets/web/loxone-slaves.js').read_text())
    lines = ['/* Generated by tools/prepare_web.py. */', '#pragma once',
             f'static const char {name}[] =']
    lines += [json.dumps(line + '\n', ensure_ascii=False).replace('??', '?\\?')
              for line in page.splitlines()]
    content = '\n'.join(lines) + ';\n'
    dest = ROOT / 'main' / header
    if CHECK:
        if not dest.exists() or dest.read_text(encoding='utf-8') != content:
            sys.exit(f'Stale embedded web page: {dest.relative_to(ROOT)}. '
                     'Run: python3 tools/prepare_web.py')
    else:
        dest.write_text(content, encoding='utf-8')


embed('template-manager.html', 'template-manager.js', '/*MANAGER_JS*/',
      'template_manager_page', 'app_template_page.h')
embed('loxone.html', 'loxone.js', '/*LOXONE_JS*/',
      'app_loxone_page', 'app_loxone_page.h')
embed('settings.html', 'settings.js', '/*SETTINGS_JS*/',
      'app_settings_page', 'app_settings_page.h')
