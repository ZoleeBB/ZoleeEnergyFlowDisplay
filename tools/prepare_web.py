#!/usr/bin/env python3
"""Embed offline template manager and settings pages from editable HTML/JS sources."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def embed(html,js,placeholder,name,header):
    page=(ROOT/'assets/web'/html).read_text().replace(placeholder,(ROOT/'assets/web'/js).read_text())
    lines=['/* Generated by tools/prepare_web.py. */','#pragma once',f'static const char {name}[] =']
    lines += [json.dumps(line+'\n',ensure_ascii=False).replace('??','?\\\\?') for line in page.splitlines()]
    (ROOT/'main'/header).write_text('\n'.join(lines)+';\n')
embed('template-manager.html','template-manager.js','/*MANAGER_JS*/','template_manager_page','app_template_page.h')
embed('settings.html','settings.js','/*SETTINGS_JS*/','app_settings_page','app_settings_page.h')
