#!/usr/bin/env python3
"""Reproducible 4-bpp LVGL fonts, including real Hungarian double accents.

Usage: python tools/prepare_fonts.py path/to/NotoSans-Regular.ttf --symbols path/to/DejaVuSans.ttf
Requires Pillow and fontTools. The font's SIL OFL license is kept under main/fonts/.
"""
import argparse
import hashlib
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
SIZES = (12, 14, 16, 18, 20, 22, 28)
CODEPOINTS = sorted(set(range(32, 127)) | set(range(160, 256)) |
                    {0x150, 0x151, 0x170, 0x171, 0x2013, 0x2014, 0x20ac, 0x2191, 0x2193})


def generate(source: Path, symbols: Path, wind_bold=False, brand=False):
    sizes = (16,20) if brand else (16,) if wind_bold else SIZES
    codepoints = sorted(set(map(ord, " Zolee Energy Folow Monitor"))) if brand else sorted(set(map(ord, " 0123456789km/h"))) if wind_bold else CODEPOINTS
    out = ROOT / 'main/fonts'
    out.mkdir(parents=True, exist_ok=True)
    fingerprint = hashlib.sha256(source.read_bytes()).hexdigest()
    symbols_fingerprint = hashlib.sha256(symbols.read_bytes()).hexdigest()
    cmaps = [TTFont(path).getBestCmap() for path in (source, symbols)]
    for cp in codepoints:
        assert cp in cmaps[cp in (0x2191, 0x2193)], f"Missing glyph U+{cp:04X}"
    for size in sizes:
        primary = ImageFont.truetype(str(source), size)
        arrows = ImageFont.truetype(str(symbols), size)
        fonts = [arrows if cp in (0x2191, 0x2193) else primary for cp in codepoints]
        bounds = [font.getbbox(chr(cp), anchor='ls') for cp, font in zip(codepoints, fonts)]
        ascent = -min(box[1] for box in bounds)
        descent = max(box[3] for box in bounds)
        bitmap = []
        descriptors = ['    {0}, /* reserved glyph 0 */']
        for cp, font, (left, top, right, bottom) in zip(codepoints, fonts, bounds):
            width, height = right-left, bottom-top
            start = len(bitmap)
            if width and height:
                img = Image.new('L', (width, height))
                ImageDraw.Draw(img).text((-left, -top), chr(cp), font=font, fill=255, anchor='ls')
                pixels = [(v*15+127)//255 for v in img.tobytes()]
                if len(pixels) % 2:
                    pixels.append(0)
                bitmap.extend((pixels[i]<<4) | pixels[i+1] for i in range(0, len(pixels), 2))
            descriptors.append('    {.bitmap_index=%d, .adv_w=%d, .box_w=%d, .box_h=%d, .ofs_x=%d, .ofs_y=%d}, /* U+%04X */' %
                               (start, round(font.getlength(chr(cp))*16), width, height, left, -bottom, cp))
        rows = ['    '+','.join(f'0x{b:02x}' for b in bitmap[i:i+24])+',' for i in range(0, len(bitmap), 24)]
        unicode_list = ','.join(str(cp-32) for cp in codepoints)
        name = f'app_font_brand_{size}' if brand else f'app_font_wind_bold_{size}' if wind_bold else f'app_font_{size}'
        license_note = 'DejaVu Sans Bold Oblique (see DejaVu-LICENSE.txt).' if brand else 'DejaVu Sans Bold (see DejaVu-LICENSE.txt).' if wind_bold else 'Noto Sans, SIL OFL 1.1 (see OFL.txt). Hungarian glyphs are actual Unicode characters.'
        text = f'''/* Generated by tools/prepare_fonts.py; source SHA256 {fingerprint}.
 * {license_note}
 * Arrows: DejaVu Sans (see DejaVu-LICENSE.txt), SHA256 {symbols_fingerprint}. */
#include "lvgl.h"
static const uint8_t bitmap[] = {{
{chr(10).join(rows)}
}};
static const lv_font_fmt_txt_glyph_dsc_t glyphs[] = {{
{chr(10).join(descriptors)}
}};
static const uint16_t unicode_list[] = {{{unicode_list}}};
static const lv_font_fmt_txt_cmap_t cmaps[] = {{{{
    .range_start=32, .range_length={codepoints[-1]-32+1}, .glyph_id_start=1,
    .unicode_list=unicode_list, .glyph_id_ofs_list=NULL,
    .list_length={len(codepoints)}, .type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY
}}}};
static const lv_font_fmt_txt_dsc_t data = {{
    .glyph_bitmap=bitmap, .glyph_dsc=glyphs, .cmaps=cmaps,
    .kern_dsc=NULL, .kern_scale=0, .cmap_num=1, .bpp=4,
    .kern_classes=0, .bitmap_format=0
}};
const lv_font_t {name} = {{
    .get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,
    .line_height={ascent+descent+2}, .base_line={descent+1},
    .subpx=LV_FONT_SUBPX_NONE, .underline_position=-1, .underline_thickness=1,
    .dsc=&data
}};
'''
        (out/f'{name}.c').write_text(text)
    print(f'Generated {len(sizes)} fonts, {len(codepoints)} glyphs each.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('font', type=Path)
    parser.add_argument('--symbols', type=Path, required=True)
    parser.add_argument('--wind-bold', action='store_true', help='Generate the 16 px wind label subset from DejaVuSans-Bold.ttf')
    parser.add_argument('--brand', action='store_true', help='Generate the fixed 16/20 px brand subset from DejaVuSans-BoldOblique.ttf')
    args = parser.parse_args()
    generate(args.font, args.symbols, args.wind_bold, args.brand)
